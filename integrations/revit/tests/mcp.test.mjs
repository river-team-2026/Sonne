import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, writeFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {setTimeout as pause} from 'node:timers/promises';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
import {createHub} from '../hub.mjs';
import {api} from '../common.mjs';

test('official MCP stdio transport lists sessions and returns the selected client result', async t => {
  const token = 'operator-'.padEnd(48, 's'), clientToken = 'windows-'.padEnd(48, 'c');
  const hub = createHub({serverToken: token, clients: [{id: 'windows', token: clientToken, label: 'Test station', allowWrites: true}]});
  await new Promise(resolve => hub.listen(0, '127.0.0.1', resolve));
  t.after(() => {hub.closeAllConnections(); hub.close();});
  const url = `http://127.0.0.1:${hub.address().port}/`;
  const folder = await mkdtemp(join(tmpdir(), 'sonne-revit-'));
  t.after(() => rm(folder, {recursive: true, force: true}));
  const config = join(folder, 'server.json');
  await writeFile(config, JSON.stringify({url, token}), {mode: 0o600});
  const mcp = new Client({name: 'sonne-test', version: '1.0.0'});
  const transport = new StdioClientTransport({command: process.execPath, args: [fileURLToPath(new URL('../mcp-server.mjs', import.meta.url)), config], stderr: 'inherit'});
  await mcp.connect(transport);
  t.after(() => mcp.close());
  const catalog = await mcp.listTools();
  assert.deepEqual(catalog.tools.map(tool => tool.name).sort(), ['revit_audit', 'revit_bulk_set', 'revit_call', 'revit_edit', 'revit_read', 'revit_room_publications', 'revit_sessions', 'revit_tools']);
  assert.ok(catalog.tools.filter(tool => !['revit_edit', 'revit_call', 'revit_bulk_set'].includes(tool.name)).every(tool => tool.annotations.readOnlyHint));
  assert.equal(catalog.tools.find(tool => tool.name === 'revit_call').annotations.readOnlyHint, false);
  assert.equal(catalog.tools.find(tool => tool.name === 'revit_edit').annotations.readOnlyHint, false);
  const device = {url, token: clientToken}, model = {documentSessionId: 'test-document', documentTitle: 'Synthetic model'};
  const tools = ['get_current_view_info', 'sonne_get_element', 'sonne_edit_element', 'create_level', 'send_code_to_revit', 'sonne_audit_parameters', 'sonne_bulk_set_parameters'].map(name => ({name, inputSchema: {type: 'object'}}));
  const {sessionId} = await api(device, 'register', {model, tools, writeEnabled: true});
  const listing = await mcp.callTool({name: 'revit_sessions', arguments: {}});
  const listed = JSON.parse(listing.content[0].text).sessions[0];
  assert.equal(listed.id, sessionId);
  assert.match(listed.target_id, /^rvt-[a-f0-9]{12}$/);
  assert.deepEqual(listed.tools, tools.map(tool => tool.name));
  const selectedSchema = await mcp.callTool({name: 'revit_tools', arguments: {target_id: listed.target_id, tool: 'create_level'}});
  assert.deepEqual(JSON.parse(selectedSchema.content[0].text).map(tool => tool.name), ['create_level']);
  const resultPromise = mcp.callTool({name: 'revit_read', arguments: {target_id: listed.target_id, tool: 'get_current_view_info', arguments: {}}});
  let job;
  for (let i = 0; i < 100 && !job; i++) {({job} = await api(device, 'poll', {sessionId, model})); if (!job) await pause(10);}
  assert.ok(job, 'MCP call should reach the Windows queue');
  const expected = {content: [{type: 'text', text: JSON.stringify({DocumentTitle: 'Synthetic model'})}]};
  await api(device, 'result', {sessionId, id: job.id, result: expected});
  assert.deepEqual(await resultPromise, expected);
  async function nextJob() {
    for (let i = 0; i < 100; i++) {const {job} = await api(device, 'poll', {sessionId, model}); if (job) return job; await pause(10);}
    assert.fail('Expected a queued tool call');
  }
  const read = mcp.callTool({name: 'revit_call', arguments: {target_id: listed.target_id, tool: 'sonne_get_element', arguments: {element_unique_id: 'sheet-uid', parameter_ids: ['-1007400']}}});
  const readJob = await nextJob();
  assert.equal(readJob.kind, 'read', 'Universal calls must classify reads on the server');
  const element = {uniqueId: 'sheet-uid', anchor_mm: null, parameters: [{id: '-1007400', value: 'Cover Sheet', readOnly: false}, {id: 'irrelevant', value: 'other'}]};
  await api(device, 'result', {sessionId, id: readJob.id, result: {content: [{type: 'text', text: JSON.stringify(element)}]}});
  const snapshot = JSON.parse((await read).content[0].text);
  assert.match(snapshot.inspection_id, /^ins-[a-f0-9]{12}$/);
  assert.equal(snapshot.parameters.length, 1);
  const editArgs = {inspection_id: snapshot.inspection_id, operation: 'set_parameter', parameter_id: '-1007400', value: 'New sheet name'};
  const edit = mcp.callTool({name: 'revit_edit', arguments: editArgs});
  const editJob = await nextJob();
  assert.equal(editJob.kind, 'write');
  assert.equal(editJob.modelId, model.documentSessionId);
  assert.equal(editJob.arguments.expected_value, 'Cover Sheet');
  assert.equal(editJob.arguments.value, 'New sheet name');
  assert.equal(editJob.arguments.element_unique_id, 'sheet-uid');
  assert.equal(Object.hasOwn(editJob.arguments, 'expected_anchor_mm'), false, 'Parameter edits must work for elements without a bounding box');
  await api(device, 'result', {sessionId, id: editJob.id, result: {content: [{type: 'text', text: '{"status":"committed"}'}]}});
  assert.ok(!(await edit).isError);
  assert.equal((await mcp.callTool({name: 'revit_edit', arguments: editArgs})).isError, true);
  assert.equal((await mcp.callTool({name: 'revit_edit', arguments: {target_id: listed.target_id, element_unique_id: 'sheet-uid', operation: 'set_parameter', parameter_id: '-1007400', expected_value: 'Cover Sheet', value: 'Uninspected change'}})).isError, true);
  const bypass = await mcp.callTool({name: 'revit_read', arguments: {session_id: sessionId, model_id: model.documentSessionId, tool: 'sonne_edit_element', arguments: {}}});
  assert.equal(bypass.isError, true);
  for (const tool of ['create_level', 'send_code_to_revit']) {
    assert.equal((await mcp.callTool({name: 'revit_read', arguments: {target_id: listed.target_id, tool}})).isError, true);
    const arguments_ = tool === 'create_level' ? {data: [{name: 'Test', elevation: 0}]} : {code: 'return document.Title;'};
    const call = mcp.callTool({name: 'revit_call', arguments: {target_id: listed.target_id, tool, arguments: arguments_}});
    const job = await nextJob();
    assert.equal(job.name, tool);
    assert.equal(job.kind, 'write');
    assert.deepEqual(job.arguments, arguments_);
    await api(device, 'result', {sessionId, id: job.id, result: expected});
    assert.deepEqual(await call, expected);
  }
  assert.equal((await mcp.callTool({name: 'revit_call', arguments: {target_id: listed.target_id, tool: 'sonne_edit_element', arguments: {}}})).isError, true);
  assert.equal((await mcp.callTool({name: 'revit_call', arguments: {target_id: listed.target_id, tool: 'unknown_tool', arguments: {}}})).isError, true);
  const audit = mcp.callTool({name: 'revit_audit', arguments: {target_id: listed.target_id, parameter: 'ALL_MODEL_INSTANCE_COMMENTS', scope: 'selection', rule: 'all'}});
  const auditJob = await nextJob();
  assert.equal(auditJob.kind, 'read');
  assert.equal(auditJob.name, 'sonne_audit_parameters');
  assert.equal(auditJob.arguments.parameter, 'ALL_MODEL_INSTANCE_COMMENTS');
  assert.equal(Object.hasOwn(auditJob.arguments, 'target_id'), false);
  const preview = {audit_id: 'aud-012345abcdef', scanned: 2, editable_matching: 2, complete: true};
  await api(device, 'result', {sessionId, id: auditJob.id, result: {content: [{type: 'text', text: JSON.stringify(preview)}]}});
  assert.deepEqual(JSON.parse((await audit).content[0].text), preview);
  const bulkArgs = {audit_id: preview.audit_id, value: 'Reviewed'};
  const bulk = mcp.callTool({name: 'revit_bulk_set', arguments: bulkArgs});
  const bulkJob = await nextJob();
  assert.equal(bulkJob.kind, 'write');
  assert.equal(bulkJob.name, 'sonne_bulk_set_parameters');
  assert.equal(bulkJob.modelId, model.documentSessionId);
  assert.deepEqual(bulkJob.arguments, bulkArgs);
  await api(device, 'result', {sessionId, id: bulkJob.id, result: expected});
  assert.ok(!(await bulk).isError);
  assert.equal((await mcp.callTool({name: 'revit_bulk_set', arguments: bulkArgs})).isError, true);
  assert.equal((await mcp.callTool({name: 'revit_bulk_set', arguments: {audit_id: 'invented', value: 'Wrong'}})).isError, true);
  assert.equal((await mcp.callTool({name: 'revit_read', arguments: {target_id: listed.target_id, tool: 'sonne_bulk_set_parameters', arguments: bulkArgs}})).isError, true);
});
